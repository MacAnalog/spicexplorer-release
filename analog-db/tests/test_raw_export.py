"""raw/ export (plan ``doc/plan_raw_export.md``): the deck writer, the catalog ``raw``/``schematic``
blocks, and the Tier-0 cross-ref + Tier-1 drift guards. All PDK-free — the committed decks are
actually SIMULATED on the base image in ``test_slow_sim.py`` (``test_L1_committed_raw_deck_simulates``).
"""

from __future__ import annotations

import json

import pytest

from spicexplorer_analog_db import catalog, export, model, paths, verify
from spicexplorer_analog_db.assemble import assemble

CIRCUIT = "amp_001_5t"


@pytest.fixture(scope="module")
def ota() -> model.Circuit:
    return model.load_circuit(CIRCUIT)


# ───────────────────────────── deck rendering ─────────────────────────────


def test_render_deck_is_self_contained(ota):
    deck = export.render_deck(ota, "ac_open_loop", "sky130", "tt")
    assert deck.startswith("** GENERATED by `analog-db export-raw` — DO NOT EDIT.")
    assert "${" not in deck  # every placeholder bound
    assert deck.rstrip().endswith(".end")  # a complete deck
    assert ".subckt amp_001_5t vdd vout vinp vinn ibias vss" in deck  # DUT inlined
    assert ".ends" in deck and "ac dec" in deck  # subckt closes + the testbench control


def test_deck_body_is_exactly_the_assembler_output(ota):
    """The banner is the ONLY thing added: the netlist body is byte-for-byte ``assemble()`` minus its
    one-line provenance header — so a committed deck can never silently diverge from the resolver."""
    asm_tail = assemble(ota, "ac_open_loop", "sky130", "tt").split("\n", 1)[1]
    assert export.render_deck(ota, "ac_open_loop", "sky130", "tt").endswith(asm_tail)


def test_every_deck_control_block_ends_with_quit():
    """Every generated testbench deck must terminate its ``.control`` block with ``quit``.

    spicelib's ngspice runner (the optimizer's `NGSpice_Wrapper`) drives ngspice in an
    interactive control session and needs a ``quit`` to close it cleanly and hand back the
    RAW — without it the optimizer can't read the result vectors. This mirrors the reference
    optimizer testbenches (``ota-improved_tb-*.spice``), which already end ``write``/``quit``.
    Guards the invariant at the *deck* level, so a future testbench template that forgets
    ``quit`` fails here regardless of which template it came from. (The `_dut.spice` subckt
    and the `.sch` schematics carry no control block and are exempt.)"""
    decks, _ = export.generate_all()
    offenders = []
    for rel, text in decks.items():
        if not rel.endswith(".spice") or rel.endswith("/_dut.spice"):
            continue
        lines = [ln.strip().lower() for ln in text.splitlines()]
        if ".control" not in lines:
            continue
        c = lines.index(".control")
        e = lines.index(".endc", c)
        body = [ln for ln in lines[c + 1 : e] if ln]
        if "quit" not in body:
            offenders.append(rel)
    assert not offenders, f"{len(offenders)} deck(s) lack a terminating quit: {offenders[:5]}"


