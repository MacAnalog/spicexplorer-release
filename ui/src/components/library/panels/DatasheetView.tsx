const MODE_LABEL: Record<string, string> = {
  block_aware: "Block-aware",
  hierarchical: "Hierarchical",
  pure: "Pure",
  abstract: "Abstract",
};

/**
 * "Open in Schematic" — an availability-driven picker over what the DB actually
 * holds for this circuit: the autogenerated export-raw renders always, plus any
 * displayable hand-drawn / paper reference images (many circuits have none —
 * the menu offers exactly what exists). Selecting opens the full-screen lightbox.
 */
function OpenSchematicMenu({ circuitId }: { circuitId: string }) {
  const [open, setOpen] = useState(false);
  const [sources, setSources] = useState<LibrarySchematicSources | null>(null);
  const [show, setShow] = useState<{ src: string; caption: string } | null>(null);
  const boxRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!open || sources?.circuit_id === circuitId) return;
    let live = true;
    api
      .librarySchematicSources(circuitId)
      .then((s) => live && setSources(s))
      .catch(() => live && setSources(null));
    return () => {
      live = false;
    };
  }, [open, circuitId, sources?.circuit_id]);

  useEffect(() => {
    if (!open) return;
    const onDown = (e: PointerEvent) => {
      if (boxRef.current && !boxRef.current.contains(e.target as Node)) setOpen(false);
    };
    window.addEventListener("pointerdown", onDown);
    return () => window.removeEventListener("pointerdown", onDown);
  }, [open]);

  const s = sources?.circuit_id === circuitId ? sources : null;
  return (
    <div ref={boxRef} className="relative">
      <Button variant="default" onClick={() => setOpen((v) => !v)}>
        Open in Schematic ▾
      </Button>
      {open && (
        <div className="absolute right-0 top-[110%] z-30 w-[300px] overflow-hidden rounded-lg border border-border bg-panel shadow-[0_10px_28px_-12px_rgba(0,0,0,0.35)]">
          {!s ? (
            <div className="px-3 py-2.5 font-mono text-[10px] text-faint">loading sources…</div>
          ) : (
            <>
              <div className="border-b border-hairline bg-bg px-3 py-1.5">
                <Eyebrow>Autogenerated (netlist2xschem)</Eyebrow>
              </div>
              {s.generated.map((g) => (
                <button
                  key={g.mode}
                  type="button"
                  onClick={() => {
                    setShow({
                      src: librarySchematicUrl(circuitId, g.mode),
                      caption: `${circuitId} · ${g.mode} (autogenerated)`,
                    });
                    setOpen(false);
                  }}
                  className="flex w-full items-center justify-between px-3 py-1.5 text-left text-[11.5px] transition hover:bg-hairline"
                >
                  <span>{MODE_LABEL[g.mode] ?? g.mode}</span>
                  <span className="font-mono text-[9px] text-faint">.svg</span>
                </button>
              ))}
              <div className="border-y border-hairline bg-bg px-3 py-1.5">
                <Eyebrow>Hand-drawn · reference</Eyebrow>
              </div>
              {s.reference.length === 0 ? (
                <div className="px-3 py-1.5 text-[10.5px] text-faint">
                  none for this circuit
                </div>
              ) : (
                s.reference.map((r) => (
                  <button
                    key={r.name}
                    type="button"
                    onClick={() => {
                      setShow({
                        src: libraryReferenceImageUrl(circuitId, r.name),
                        caption: `${circuitId} · reference/${r.name}`,
                      });
                      setOpen(false);
                    }}
                    className="flex w-full items-center justify-between gap-2 px-3 py-1.5 text-left transition hover:bg-hairline"
                  >
                    <span className="min-w-0 truncate font-mono text-[10.5px]">{r.name}</span>
                  </button>
                ))
              )}
              {s.reference_other.length > 0 && (
                <div className="border-t border-hairline px-3 py-1.5 text-[9.5px] leading-relaxed text-faint">
                  +{s.reference_other.length} vendored source
                  {s.reference_other.length === 1 ? "" : "s"} without a render (
                  {s.reference_other.slice(0, 2).join(", ")}
                  {s.reference_other.length > 2 ? ", …" : ""})
                </div>
              )}
            </>
          )}
        </div>
      )}
      {show && (
        <Lightbox src={show.src} alt={show.caption} caption={show.caption} onClose={() => setShow(null)} />
      )}
    </div>
  );
}

/** "Use as project" — seeds a real WORK_ROOT project from this catalog circuit
 *  (backend P5 route), switches to it, and lands on Setup. */
function UseAsProjectButton({ circuitId }: { circuitId: string }) {
  const router = useRouter();
  const switchProject = useProjectStore((s) => s.switchProject);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const start = async () => {
    setBusy(true);
    setError(null);
    try {
      const seeded = await api.libraryStartProject(circuitId, {});
      await switchProject(seeded.id);
      router.push("/setup" as Route);
    } catch (e) {
      setError(e instanceof Error ? e.message : "failed to seed the project");
      setBusy(false);
    }
  };

  return (
    <div className="flex flex-col items-end gap-1">
      <Button variant="primary" onClick={() => void start()} disabled={busy}>
        {busy ? "Seeding project…" : "Use as project"}
      </Button>
      {error && <span className="max-w-[260px] truncate font-mono text-[9.5px] text-danger" title={error}>⚠ {error}</span>}
    </div>
  );
}

