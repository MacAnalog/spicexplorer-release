# ───────────────────────────── the pure generator ─────────────────────────────


def test_generate_all_is_deterministic():
    a, _ = export.generate_all()
    b, _ = export.generate_all()
    assert a == b and len(a) > 100


def test_generate_skips_disabled_and_unbound(ota):
    decks, skipped = export.generate_all()
    reasons = dict(skipped)
    # a scaffolded `enabled: false` analysis is skipped with a reason, not exported
    assert reasons.get("amp_012_peng_tcfc/dc_op") == "disabled"
    assert "raw/amp_012_peng_tcfc/sky130/dc_op.spice" not in decks
    # tan_clia binds only sky130 + gf180 → no ihp deck at all (not even an error)
    assert "raw/amp_017_tan_clia/sky130/ac_open_loop.spice" in decks
    assert "raw/amp_017_tan_clia/ihp-sg13g2/ac_open_loop.spice" not in decks
    # every amp_001_5t analysis × pdk + a _dut is present
    for pdk in ota.pdks:
        assert f"raw/amp_001_5t/{pdk}/_dut.spice" in decks
        for aid in ota.analyses:
            assert f"raw/amp_001_5t/{pdk}/{aid}.spice" in decks


def test_deck_index_groups_by_pdk_and_testbench():
    idx = export.deck_index()
    sky = idx["amp_001_5t"]["sky130"]
    assert sky["ac_open_loop"] == "raw/amp_001_5t/sky130/ac_open_loop.spice"
    assert "_dut" in sky and set(idx["amp_001_5t"]) == {"ihp-sg13g2", "sky130", "gf180mcu"}


# ───────────────────────────── xschem schematic (.sch) ─────────────────────────────


def test_generate_emits_one_circuit_schematic(ota):
    """Each circuit gets a single deterministic ``<id>.sch`` at circuit level, drawn from the ref PDK."""
    pytest.importorskip("spicexplorer_netlist2xschem")
    decks, _ = export.generate_all([CIRCUIT])
    rel = "raw/amp_001_5t/amp_001_5t.sch"
    assert rel in decks
    assert decks[rel].startswith("v {xschem version=")  # the xschem header
    assert f"T {{{CIRCUIT}}}" in decks[rel]  # title block carries the circuit id
    assert export.sch_path(ota).name == "amp_001_5t.sch"  # one per circuit, not per pdk


def test_schematic_is_not_a_testbench_in_the_index():
    """The ``.sch`` lives in the tree (and is drift-guarded) but never appears as a testbench deck."""
    pytest.importorskip("spicexplorer_netlist2xschem")
    idx = export.deck_index([CIRCUIT])
    for pdk_tbs in idx[CIRCUIT].values():
        assert all(rel.endswith(".spice") for rel in pdk_tbs.values())
        assert not any(k.endswith(".sch") or k == "amp_001_5t" for k in pdk_tbs)


# ───────────────────────────── catalog integration ─────────────────────────────


def test_catalog_carries_raw_and_schematic_blocks():
    cat = json.loads(paths.catalog_path().read_text())
    e = next(c for c in cat["circuits"] if c["id"] == CIRCUIT)
    assert set(e["raw"]) == {"ihp-sg13g2", "sky130", "gf180mcu"}
    assert e["raw"]["sky130"]["noise"] == "raw/amp_001_5t/sky130/noise.spice"
    # schematics are reference-only pointers to files that exist (amp_001_5t has authored xschem)
    assert e["schematic"]["abstract"] == "circuits/amp_001_5t/abstract/schematic.svg"
    assert e["schematic"]["ihp-sg13g2"].endswith(".svg")


def test_catalog_raw_paths_all_exist_on_disk():
    cat = json.loads(paths.catalog_path().read_text())
    root = paths.db_root()
    for c in cat["circuits"]:
        for tbs in c.get("raw", {}).values():
            for rel in tbs.values():
                assert (root / rel).is_file(), f"catalog → missing {rel}"


def test_catalog_is_deterministic_with_raw_block():
    assert paths.catalog_path().read_text() == catalog.catalog_json()


